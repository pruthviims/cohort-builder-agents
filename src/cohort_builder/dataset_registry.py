"""Registry of imported (CSV) datasets: staging, versioning, mapping, registration.

Lifecycle of one ingestion (one immutable version of a dataset), as recorded in meta.dataset_version:

    allocating      the version number is reserved (own short transaction; UNIQUE (dataset, version))
    staged          files typed and loaded into stg_<dataset>_v<N>                          [transaction T]
    profile_pending mapping validated, semantic views sem_<dataset>_v<N> built, profile kept in the DB  [T]
    registered      the profile FILE <dataset>__v<N>.yaml was written and verified (after T committed)
    profile_failed  T committed but the profile file could not be written; nothing is selectable
    failed          T rolled back (problems recorded without cell values)

* Staging, mapping and the status change run in ONE database transaction T; any failure rolls back, so no
  partial tables or registrations remain.
* The selectable profile is a FILE. A database transaction and a file write cannot be atomic together, so
  the file is published only after T commits, and the status becomes 'registered' only after the file is
  in place (written to a temp file, then renamed). If the process stops in between, the version stays
  'profile_pending' / 'profile_failed'; `reconcile()` (CLI: `cohort-builder csv reconcile`) republishes it
  from the profile stored in the database, removes stale generated files and repairs the latest pointer.
* Activation re-checks the file against the database (`verify_registered_profile`): a profile whose
  version is not 'registered', whose content hash differs, or an unpinned `<dataset>.yaml` that does not
  point at the latest registered version is refused. A stale or missing file is never used silently.
* Versions are immutable. Re-using a dataset name requires `new_version=True`; nothing is overwritten.
  `<dataset>.yaml` points at the latest registered version; `<dataset>__v<N>.yaml` pins a version.
* Built-in dataset names (ontology/datasets) and internal schema names are reserved.
* A registered dataset is a normal dataset profile: select it with --dataset / CB_DATASET. All cohort
  safeguards (validation, approval, deterministic compilation, guards, suppression, audit) apply unchanged.
"""

