@dataclass
class Upload:
    """In-memory CSV content (API uploads). `name` must be a bare file name."""

    name: str
    text: str


def load_mapping(text: str) -> DatasetMapping:
    """Strict YAML (duplicate keys, anchors/aliases and oversized files refused) -> validated mapping."""
    from .proxy import load_yaml_strict  # strict loader rejects duplicate keys

    if len(text) > MAX_MAPPING_CHARS:
        raise IngestError(
            f"mapping file is larger than {MAX_MAPPING_CHARS} characters",
            [{"code": "invalid_mapping", "message": "mapping file too large"}],
        )
    try:
        has_alias = any(isinstance(ev, (yaml.AliasEvent,)) or getattr(ev, "anchor", None) for ev in yaml.parse(text))
    except yaml.YAMLError as exc:
        raise IngestError(
            "mapping file is not valid YAML", [{"code": "invalid_mapping", "message": "YAML syntax error"}]
        ) from exc
    if has_alias:
        raise IngestError(
            "mapping files may not use YAML anchors or aliases (write every value out)",
            [{"code": "invalid_mapping", "message": "YAML anchors/aliases are not allowed"}],
        )
    data = load_yaml_strict(text)
    if not isinstance(data, dict):
        raise IngestError("a mapping file must be a YAML mapping")
    return DatasetMapping.model_validate(data)


def parse_type_overrides(specs: Sequence[str]) -> dict[str, dict[str, str]]:
    """'table.column=TYPE' strings (CLI) -> {table: {column: TYPE}}."""
    out: dict[str, dict[str, str]] = {}
    for spec in specs:
        target, sep, typ = spec.partition("=")
        table, dot, column = target.strip().partition(".")
        if not sep or not dot or not table or not column or not typ.strip():
            raise IngestError(
                "type overrides look like TABLE.COLUMN=TYPE (e.g. claims.member_id=VARCHAR)",
                [{"code": "invalid_override", "message": "malformed type override"}],
            )
        out.setdefault(table, {})[column.strip()] = typ.strip().upper()
    return out


def _profile_body(profile: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in profile.items() if k != "name"}


def profile_hash(profile: dict[str, Any]) -> str:
    """Hash of a generated profile, independent of the file name it is published under."""
    return sha(_profile_body(profile))


def verify_registered_profile(con: duckdb.DuckDBPyConnection, profile: dict[str, Any], profile_name: str) -> None:
    """Refuse a CSV-import profile that is not backed by a 'registered' version in THIS database, whose
    content differs from what was registered, or (unpinned name) that is not the latest registered version.
    Built-in profiles (no `source.kind: csv`) are not affected."""
    src = profile.get("source") or {}
    if not isinstance(src, dict) or src.get("kind") != "csv":
        return
    dataset, version = src.get("dataset"), src.get("version")
    hint = "run `cohort-builder csv reconcile` (or re-import the data into this database)"
    row = con.execute(
        "SELECT status, profile_hash FROM meta.dataset_version WHERE dataset = ? AND version = ?",
        [dataset, version],
    ).fetchone()
    if row is None:
        raise ValueError(f"dataset profile {profile_name!r} is not registered in this database; {hint}")
    status, expected = row
    if status != "registered":
        raise ValueError(f"dataset profile {profile_name!r}: version {version} is {status!r}, not registered; {hint}")
    body = _profile_body(profile)
    if expected not in (sha(body), sha({**body, "name": dataset})):  # second form: profiles before profile_json
        raise ValueError(f"dataset profile {profile_name!r} does not match the registered version (modified or stale)")
    if profile_name == dataset:
        latest = con.execute(
            "SELECT max(version) FROM meta.dataset_version WHERE dataset = ? AND status = 'registered'", [dataset]
        ).fetchone()
        if latest is None or latest[0] != version:
            raise ValueError(
                f"dataset profile {profile_name!r} points at v{version} but the latest registered version is "
                f"v{latest[0] if latest else '?'}; {hint}"
            )


class DatasetRegistry:
    def __init__(
        self, con: duckdb.DuckDBPyConnection, ontology_dir: Path, local_dir: Path, store: MetadataStore | None = None
    ):
        self.con = con
        init_schemas(con)
        self.ontology_dir = Path(ontology_dir)
        self.local_dir = Path(local_dir)
        self.store = store or MetadataStore(con)
        self.ont = Ontology.load(self.ontology_dir)  # entities, vocab schema (dataset-independent parts)
        try:  # version numbers are allocated through this constraint (concurrent imports cannot share one)
            con.execute(
                "CREATE UNIQUE INDEX IF NOT EXISTS dataset_version_unique ON meta.dataset_version (dataset, version)"
            )
            self.unique_versions = True
        except duckdb.Error:  # pre-existing duplicate rows (older databases): refuse new imports, see ingest()
            self.unique_versions = False

    # ---- failure-injection seams (tests) ----------------------------------------------------------
    def _tx(self, stmt: str) -> None:
        self.con.execute(stmt)

    _replace: Callable[[str | Path, str | Path], None] = staticmethod(os.replace)

    # ---- names and versions --------------------------------------------------------------------
    def builtin_names(self) -> set[str]:
        return {p.stem for p in (self.ontology_dir / self.ont.domain["datasets_dir"]).glob("*.yaml")}

    def check_dataset_name(self, name: str) -> str:
        validate_name(name, "dataset name")
        if len(name) > 40:
            raise IngestError("dataset names are limited to 40 characters")
        if name in RESERVED or name in self.builtin_names():
            raise IngestError(
                f"dataset name {name!r} is reserved (built-in profile or internal schema)",
                [{"code": "reserved_name", "message": "reserved dataset name"}],
            )
        return name

    def versions(self, name: str) -> list[dict[str, Any]]:
        cur = self.con.execute(
            "SELECT ingest_id, dataset, version, status, created_by, created_at, registered_at, staging_schema, "
            "semantic_schema, files_json, mapping_hash, validation_json, profile_hash, snapshot, software_version, "
            "errors_json, profile_json IS NOT NULL AS has_profile FROM meta.dataset_version WHERE dataset = ? "
            "ORDER BY version DESC, created_at DESC",
            [name],
        )
        cols = [d[0] for d in cur.description]
        out = []
        for r in cur.fetchall():
            row = dict(zip(cols, r, strict=True))
            for k in ("files_json", "validation_json", "errors_json"):
                row[k.removesuffix("_json")] = json.loads(row.pop(k) or "null")
            out.append(row)
        return out

    def _usable(self, name: str) -> list[dict[str, Any]]:
        return [v for v in self.versions(name) if v["status"] in USABLE]

    def _allocate(self, dataset: str, ingest_id: str, actor: str, new_version: bool) -> int:
        """Reserve the next version number (committed immediately; the unique index arbitrates races)."""
        if not self.unique_versions:
            raise IngestError(
                "meta.dataset_version contains duplicate (dataset, version) rows; resolve them before importing",
                [{"code": "duplicate_versions", "message": "version table needs repair"}],
            )
        for attempt in range(ALLOCATION_ATTEMPTS):
            if attempt:  # back off with jitter so racing imports stop colliding on the same number
                time.sleep(random.uniform(0.005, 0.02) * min(attempt, 10))
            version = (
                fetch_count(
                    self.con, "SELECT coalesce(max(version), 0) FROM meta.dataset_version WHERE dataset = ?", [dataset]
                )
                + 1
            )
            try:
                self.con.execute(
                    "INSERT INTO meta.dataset_version (ingest_id, dataset, version, status, created_by, created_at, "
                    "software_version) VALUES (?,?,?,'allocating',?,?,?)",
                    [ingest_id, dataset, version, actor, now(), __version__],
                )
            except (duckdb.ConstraintException, duckdb.TransactionException):
                # another import took this number (DuckDB reports a concurrent unique-key conflict at commit
                # time as a TransactionException); try the next one
                continue
            break
        else:
            raise IngestError(
                "could not allocate a version number (concurrent imports); retry",
                [{"code": "version_conflict", "message": "version allocation failed"}],
            )
        others = self.con.execute(
            # only LOWER versions count: when several first imports race, the lowest allocation wins and
            # every other one is refused (deterministic, never zero or two winners)
            "SELECT version, status FROM meta.dataset_version WHERE dataset = ? AND ingest_id <> ? AND version < ? "
            f"AND status IN ({', '.join('?' for _ in LIVE)}) ORDER BY version DESC",
            [dataset, ingest_id, version, *LIVE],
        ).fetchall()
        if others and not new_version:
            v, st = others[0]
            problems = [{"code": "dataset_exists", "message": "dataset exists"}]
            self._mark_failed(ingest_id, problems, [])
            raise IngestError(
                f"dataset {dataset!r} already exists (v{v}, {st}); pass --new-version to import a new immutable "
                "version (nothing is overwritten)",
                problems,
            )
        return version

    # ---- ingestion -----------------------------------------------------------------------------
    def ingest(
        self,
        dataset: str,
        files: Sequence[tuple[str | None, Path | Upload]],
        actor: str,
        mapping: DatasetMapping | None = None,
        new_version: bool = False,
        dry_run: bool = False,
        null_values: tuple[str, ...] = (),
        max_bytes: int | None = None,
        column_types: dict[str, dict[str, str]] | None = None,
    ) -> dict[str, Any]:
        self.check_dataset_name(dataset)
        if not files:
            raise IngestError("give at least one CSV file")
        overrides = self._check_overrides(column_types)
        existing = [v for v in self.versions(dataset) if v["status"] in LIVE]
        if existing and not new_version and not dry_run:
            v = existing[0]
            raise IngestError(
                f"dataset {dataset!r} already exists (v{v['version']}, {v['status']}); pass "
                "--new-version to import a new immutable version (nothing is overwritten)",
                [{"code": "dataset_exists", "message": "dataset exists"}],
            )
        ingest_id = str(uuid.uuid4())
        if dry_run:
            version = max((v["version"] for v in self.versions(dataset)), default=0) + 1
        else:
            version = self._allocate(dataset, ingest_id, actor, new_version)
        stg, sem = f"stg_{dataset}_v{version}", f"sem_{dataset}_v{version}"
        if dry_run:  # never collide with the schemas of a real import of the same version running meanwhile
            suffix = uuid.uuid4().hex[:8]
            stg, sem = f"{stg}_dry{suffix}", f"{sem}_dry{suffix}"
        limit = max_bytes or max_bytes_from_env()
        report: dict[str, Any] = {
            "dataset": dataset,
            "version": version,
            "ingest_id": ingest_id,
            "dry_run": dry_run,
            "staging_schema": stg,
            "files": [],
            "mapping": None,
        }
        tables: list[str] = []
        profile: dict[str, Any] = {}
        status = "staged"
        self._tx("BEGIN")
        try:
            self.con.execute(f"CREATE SCHEMA {qi(stg)}")
            for table, src in files:
                if isinstance(src, Upload):
                    info: FileInfo = check_text(src.name, src.text, limit)
                    name = validate_name(table or default_table_name(Path(src.name)))
                else:
                    info = check_file(Path(src), limit)
                    name = validate_name(table or default_table_name(Path(src)))
                if name in tables:
                    raise IngestError(
                        f"table name {name!r} is used for two files",
                        [{"code": "duplicate_table", "message": "two files map to one table"}],
                    )
                tables.append(name)
                stream = text_stream(src.text) if isinstance(src, Upload) else open_text(Path(src))
                try:
                    with stream:
                        prof: TableProfile = stage_table(
                            self.con, stg, name, stream, info, null_values, overrides.get(name)
                        )
                except IngestError as exc:
                    raise IngestError(f"{info.name}: {exc}", [{**p, "file": info.name} for p in exc.problems]) from exc
                report["files"].append(prof.as_dict())
            if unknown := sorted(set(overrides) - set(tables)):
                raise IngestError(
                    f"type overrides name tables that were not imported: {unknown}",
                    [{"code": "invalid_override", "message": "override for an unknown table"}],
                )
            validation = None
            if mapping is not None:
                validation, profile = self._register(dataset, version, stg, sem, mapping, report["files"], ingest_id)
                report["mapping"] = validation
                status = "profile_pending"
            if dry_run:
                report["status"] = "dry_run"
                self._tx("ROLLBACK")
                return report
            self.con.execute(
                "UPDATE meta.dataset_version SET status=?, staging_schema=?, semantic_schema=?, files_json=?, "
                "mapping_json=?, mapping_hash=?, validation_json=?, profile_hash=?, profile_json=?, snapshot=? "
                "WHERE ingest_id=?",
                [
                    status,
                    stg,
                    sem if mapping else None,
                    dumps(report["files"]),
                    dumps(mapping.model_dump(mode="json")) if mapping else None,
                    mapping.content_hash() if mapping else None,
                    dumps(validation),
                    profile_hash(profile) if profile else None,
                    dumps(profile) if profile else None,
                    profile.get("snapshot_sql"),
                    ingest_id,
                ],
            )
            self._tx("COMMIT")
        except Exception as exc:
            self._rollback()
            problems = (
                exc.problems
                if isinstance(exc, IngestError)
                else [{"code": "internal", "message": f"{type(exc).__name__} during ingestion"}]
            )
            if not dry_run:
                self._mark_failed(ingest_id, problems, report["files"])
            self.store.audit(
                actor,
                "dataset.ingest",
                "dataset",
                f"{dataset}:v{version}",
                "failed",
                None,
                {"problems": len(problems), "dry_run": dry_run},
            )
            if isinstance(exc, IngestError):
                raise
            raise IngestError(f"ingestion failed ({type(exc).__name__}); nothing was registered", problems) from exc
        publish_error: IngestError | None = None
        if mapping is not None:
            try:
                self._publish(dataset, version, ingest_id, profile)
                status = "registered"
            except IngestError as exc:
                publish_error = exc
                status = self._status(ingest_id)
        report["status"] = status
        self.store.audit(
            actor,
            "dataset.ingest",
            "dataset",
            f"{dataset}:v{version}",
            "success" if publish_error is None else "partial",
            None,
            {"status": status, "tables": tables, "files": [f["sha256"] for f in report["files"]]},
        )
        if publish_error is not None:
            raise publish_error
        report["profile"] = dataset if status == "registered" else None
        return report

    def _check_overrides(self, column_types: dict[str, dict[str, str]] | None) -> dict[str, dict[str, str]]:
        """Shape checks only; each column's values are validated during staging."""
        if not column_types:
            return {}
        if not isinstance(column_types, dict) or sum(len(v) for v in column_types.values()) > MAX_TYPE_OVERRIDES:
            raise IngestError(_BAD_TYPES, [{"code": "invalid_override", "message": "malformed column_types"}])
        for table, cols in column_types.items():
            validate_name(table)
            if not isinstance(cols, dict) or not all(
                isinstance(k, str) and isinstance(v, str) for k, v in cols.items()
            ):
                raise IngestError(_BAD_TYPES, [{"code": "invalid_override", "message": "malformed column_types"}])
        return {t: {c: v.upper() for c, v in cols.items()} for t, cols in column_types.items()}

    def register_mapping(
        self, dataset: str, mapping: DatasetMapping, actor: str, version: int | None = None
    ) -> dict[str, Any]:
        """Register a mapping for a staged version (same version, no new data)."""
        usable = self._usable(dataset)
        row = next((v for v in usable if version is None or v["version"] == version), None)
        if row is None:
            raise IngestError(f"no staged version of dataset {dataset!r}" + (f" v{version}" if version else ""))
        if row["status"] != "staged":
            same = row["mapping_hash"] == mapping.content_hash()
            if same and row["status"] == "registered":
                return {"dataset": dataset, "version": row["version"], "status": "registered", "unchanged": True}
            if same:
                raise IngestError(
                    f"{dataset} v{row['version']} is {row['status']}: its profile was not published; run "
                    "`cohort-builder csv reconcile`",
                    [{"code": "profile_not_published", "message": "run reconcile"}],
                )
            raise IngestError(
                f"{dataset} v{row['version']} is already registered with a different mapping; ingest "
                "a new version to change it (registered mappings are immutable)",
                [{"code": "mapping_exists", "message": "version already registered"}],
            )
        v, stg = row["version"], row["staging_schema"]
        sem = f"sem_{dataset}_v{v}"
        self._tx("BEGIN")
        try:
            validation, profile = self._register(dataset, v, stg, sem, mapping, row["files"], row["ingest_id"])
            self.con.execute(
                "UPDATE meta.dataset_version SET status='profile_pending', semantic_schema=?, mapping_json=?, "
                "mapping_hash=?, validation_json=?, profile_hash=?, profile_json=?, snapshot=? WHERE ingest_id=? "
                "AND status='staged'",
                [
                    sem,
                    dumps(mapping.model_dump(mode="json")),
                    mapping.content_hash(),
                    dumps(validation),
                    profile_hash(profile),
                    dumps(profile),
                    profile["snapshot_sql"],
                    row["ingest_id"],
                ],
            )
            self._tx("COMMIT")
        except Exception:
            self._rollback()
            self.store.audit(actor, "dataset.register", "dataset", f"{dataset}:v{v}", "failed", None, {})
            raise
        try:
            self._publish(dataset, v, row["ingest_id"], profile)
        except IngestError:
            self.store.audit(actor, "dataset.register", "dataset", f"{dataset}:v{v}", "partial", None, {})
            raise
        self.store.audit(
            actor,
            "dataset.register",
            "dataset",
            f"{dataset}:v{v}",
            "success",
            None,
            {"mapping_hash": mapping.content_hash()},
        )
        return {"dataset": dataset, "version": v, "status": "registered", "mapping": validation}

    def _rollback(self) -> None:
        try:
            self._tx("ROLLBACK")
        except duckdb.Error:
            pass  # no transaction open (e.g. COMMIT itself failed and DuckDB already rolled back)

    def _status(self, ingest_id: str) -> str:
        row = self.con.execute("SELECT status FROM meta.dataset_version WHERE ingest_id = ?", [ingest_id]).fetchone()
        return str(row[0]) if row else "unknown"

    # ---- mapping -> semantic layer + checks -----------------------------------------------------
    def _schema(self, stg: str) -> Schema:
        rows = self.con.execute(
            "SELECT table_name, column_name, data_type FROM information_schema.columns WHERE table_schema = ? "
            "ORDER BY table_name, ordinal_position",
            [stg],
        ).fetchall()
        out: Schema = {}
        for t, c, typ in rows:
            out.setdefault(t, {})[c] = str(typ).upper()
        return out

    def _vocabulary_versions(self, vocabs: list[str]) -> dict[str, str | None]:
        vs = self.ont.vocab_schema()
        out: dict[str, str | None] = {}
        for v in vocabs:
            loaded = fetch_count(self.con, f"SELECT count(*) FROM {vs}.concept WHERE vocabulary_id = ?", [v])
            row = self.con.execute(
                f"SELECT max(vocabulary_version) FROM {vs}.vocabulary WHERE vocabulary_id = ?", [v]
            ).fetchone()
            out[v] = (row[0] if row and row[0] else "unknown version") if loaded else None
        return out

    def _register(
        self,
        dataset: str,
        version: int,
        stg: str,
        sem: str,
        m: DatasetMapping,
        files: list[dict[str, Any]],
        ingest_id: str,
    ) -> tuple[dict[str, Any], dict[str, Any]]:
        full = {t: c for t, c in self._schema(stg).items() if t != "person_map"}
        row_ref = {t for t, cols in full.items() if SOURCE_ROW in cols}
        schema = {t: {c: typ for c, typ in cols.items() if c != SOURCE_ROW} for t, cols in full.items()}
        errors, warnings = validate_mapping(m, schema, self.ont)
        if errors:
            raise IngestError(
                "mapping does not fit the imported tables: " + "; ".join(errors),
                [{"code": "invalid_mapping", "message": e} for e in errors],
            )
        use_map = needs_person_map(m, schema)
        if use_map:
            exists = fetch_count(
                self.con,
                "SELECT count(*) FROM information_schema.tables WHERE table_schema = ? AND table_name = 'person_map'",
                [stg],
            )
            if not exists:
                self.con.execute(person_map_sql(m, stg))
        for stmt in semantic_sql(m, stg, sem, use_map, self.ont.vocab_schema(), row_ref):
            self.con.execute(stmt)
        strategies = code_strategies(m)
        vocabularies = self._vocabulary_versions(sorted({v for v, _ in strategies.values()}))
        checks, more_errors, more_warnings = self._data_checks(m, stg, sem, use_map)
        for v, ver in vocabularies.items():
            if ver is None:
                more_warnings.append(f"vocabulary {v} is not loaded in this database; no {v} code can be mapped")
        if more_errors:
            raise IngestError(
                "mapped data cannot be used: " + "; ".join(more_errors),
                [{"code": "invalid_data", "message": e} for e in more_errors],
            )
        normalization = {ent: {"vocabulary": v, "strategy": s} for ent, (v, s) in strategies.items()}
        source = {
            "kind": "csv",
            "dataset": dataset,
            "version": version,
            "ingest_id": ingest_id,
            "files": [
                {"table": f["table"], "file": f["file"], "sha256": f["sha256"], "rows": f["rows"]} for f in files
            ],
            "mapping_hash": m.content_hash(),
            "content_hash": sha(sorted(f["sha256"] for f in files) + [m.content_hash()]),
            "code_normalization": normalization,
            "vocabularies": vocabularies,
            "software_version": __version__,
        }
        profile = build_profile(m, dataset, version, stg, sem, use_map, self.ont, source, row_ref)
        all_warnings = warnings + more_warnings
        validation = {
            "valid": True,
            "errors": [],
            "warnings": all_warnings,
            "checks": checks,
            "summary": self._summary(m, checks, all_warnings),
            "entities": sorted(m.entities),
            "observation": m.observation.mode,
            "absence_inference": m.observation.absence_inference,
            "surrogate_person_ids": use_map,
            "code_normalization": {
                ent: {**d, "rule": NORMALIZATIONS[d["strategy"]]} for ent, d in normalization.items()
            },
            "vocabularies": vocabularies,
        }
        return validation, profile

    def _summary(self, m: DatasetMapping, checks: dict[str, Any], warnings: list[str]) -> dict[str, Any]:
        """Plain-language suitability: what cohort criteria can and cannot use."""
        unavailable = sorted(set(self.ont.entities) - set(m.entities))
        no_concepts = [e for e in sorted(m.entities) if checks[e]["concept_mapping"]["mapped_rows"] == 0]
        limitations = []
        if unavailable:
            limitations.append(f"criteria on {', '.join(unavailable)} are refused (not mapped)")
        if no_concepts:
            limitations.append(f"criteria on {', '.join(no_concepts)} will find nobody (no row maps to a concept)")
        if m.observation.mode == "none":
            limitations.append("observation windows and 'no record' criteria are refused (no observation periods)")
        elif m.observation.mode == "activity":
            limitations.append("observation is inferred from activity; absence of a record is weak evidence")
        return {
            "suitable_for_cohorts": True,  # hard errors stop registration; reaching here means usable
            "entities_with_concepts": [e for e in sorted(m.entities) if e not in no_concepts],
            "entities_without_concepts": no_concepts,
            "entities_not_mapped": unavailable,
            "limitations": limitations,
            "warnings": len(warnings),
        }

    def _data_checks(
        self, m: DatasetMapping, stg: str, sem: str, use_map: bool
    ) -> tuple[dict[str, Any], list[str], list[str]]:
        """Counts only (never values). Per entity, staged rows fall into exactly one of:
        missing_patient_id -> missing_start_date -> invalid_start_date -> usable (checked in that order), so
        staged = missing_patient_id + missing_start_date + invalid_start_date + usable. Concept mapping is
        then measured on usable rows only (mapped + unmapped = usable); `view_rows` can exceed usable when one
        source code maps to several standard concepts (each becomes a row)."""
        con, vs = self.con, self.ont.vocab_schema()
        errors: list[str] = []
        warnings: list[str] = []
        checks: dict[str, Any] = {}
        persons = fetch_count(con, f"SELECT count(DISTINCT person_id) FROM {qi(sem)}.person")
        conflicting = fetch_count(con, f"SELECT count(*) - count(DISTINCT person_id) FROM {qi(sem)}.person")
        pm = m.person
        missing_pid = fetch_count(
            con, f"SELECT count(*) FROM {qi(stg)}.{qi(pm.table)} WHERE {qi(pm.person_column)} IS NULL"
        )
        implausible_birth = fetch_count(
            con,
            f"SELECT count(*) FROM {qi(sem)}.person WHERE year_of_birth < 1900 OR "
            "year_of_birth > EXTRACT(YEAR FROM current_date)",
        )
        checks["person"] = {
            "persons": persons,
            "conflicting_records": conflicting,
            "rows_missing_patient_id": missing_pid,
            "implausible_year_of_birth": implausible_birth,
        }
        if implausible_birth:
            warnings.append(
                f"person: {implausible_birth} person(s) have a year of birth before 1900 or in the future "
                "(kept as recorded; age criteria use it)"
            )
        if persons == 0:
            errors.append("the person table has no usable rows")
        if conflicting:
            errors.append(f"{conflicting} person id(s) have conflicting gender or birth year across rows")
        if missing_pid:
            warnings.append(f"person: {missing_pid} row(s) have no patient id and were excluded")

        for entity, e in sorted(m.entities.items()):
            x = entity_exprs(e, "t")
            tbl = f"{qi(stg)}.{qi(e.table)} t"
            view = f"{qi(sem)}.{qi(_view(entity))}"
            ok = f"{x.person} IS NOT NULL AND {x.start} IS NOT NULL"
            end_sql = (
                f"count(*) FILTER (WHERE {ok} AND {x.end_raw} IS NOT NULL AND {x.end} IS NULL), "
                f"count(*) FILTER (WHERE {ok} AND {x.end} < {x.start})"
                if x.end_raw
                else "0, 0"
            )
            r = con.execute(
                f"SELECT count(*), count(*) FILTER (WHERE {x.person} IS NULL), "
                f"count(*) FILTER (WHERE {x.person} IS NOT NULL AND {x.start_raw} IS NULL), "
                f"count(*) FILTER (WHERE {x.person} IS NOT NULL AND {x.start_raw} IS NOT NULL AND {x.start} IS NULL), "
                f"count(*) FILTER (WHERE {ok}), {end_sql}, "
                f"count(*) FILTER (WHERE {ok} AND ({x.start} < DATE '{EARLIEST_PLAUSIBLE_DATE}' OR "
                f"{x.start} > current_date)) FROM {tbl}"
            ).fetchone()
            staged, no_pid, no_date, bad_date, usable, bad_end, end_before, out_of_range = (
                int(v) for v in (r or (0,) * 8)
            )
            rows = {
                "staged_rows": staged,
                "missing_patient_id": no_pid,
                "missing_start_date": no_date,
                "invalid_start_date": bad_date,
                "usable_rows": usable,
                "invalid_end_date": bad_end,
                "end_before_start": end_before,
                "start_date_out_of_range": out_of_range,
            }
            concept = self._concept_checks(e, x, tbl, ok, sem, vs, usable)
            view_rows = fetch_count(con, f"SELECT count(*) FROM {view}")
            orphans = fetch_count(
                con,
                f"SELECT count(DISTINCT person_id) FROM {view} v WHERE NOT EXISTS "
                f"(SELECT 1 FROM {qi(sem)}.person p WHERE p.person_id = v.person_id)",
            )
            values: dict[str, int] = {}
            if e.value_column:
                values["missing_value"] = fetch_count(
                    con, f"SELECT count(*) FROM {tbl} WHERE {ok} AND t.{qi(e.value_column)} IS NULL"
                )
                values["unmapped_unit"] = fetch_count(
                    con, f"SELECT count(*) FROM {view} WHERE value_as_number IS NOT NULL AND unit_concept_id IS NULL"
                )
            checks[entity] = {
                "rows": rows,
                "concept_mapping": concept,
                "view_rows": view_rows,
                "persons_missing_from_person_table": orphans,
                **({"values": values} if values else {}),
            }
            if usable == 0:
                errors.append(
                    f"{entity}: no usable rows ({no_pid} without patient id, {no_date} without start date, "
                    f"{bad_date} with an invalid start date)"
                )
                continue
            dropped = no_pid + no_date + bad_date
            if dropped:
                warnings.append(
                    f"{entity}: {dropped} of {staged} row(s) excluded ({no_pid} without patient id, {no_date} "
                    f"without start date, {bad_date} with an invalid start date)"
                )
            if bad_end:
                warnings.append(f"{entity}: {bad_end} row(s) have an invalid end date (end treated as missing)")
            if out_of_range:
                warnings.append(
                    f"{entity}: {out_of_range} usable row(s) start before {EARLIEST_PLAUSIBLE_DATE} or in the future "
                    "(kept as recorded; check the source or date_format)"
                )
            if end_before:
                warnings.append(f"{entity}: {end_before} row(s) end before they start")
            mapped = concept["mapped_rows"]
            if mapped == 0:
                warnings.append(
                    f"{entity}: no row maps to a standard concept; criteria on {entity} will find nothing "
                    "(check the vocabulary or concept column)"
                )
            elif mapped < usable:
                warnings.append(
                    f"{entity}: {usable - mapped} of {usable} usable row(s) do not map to a standard concept "
                    f"(coverage {concept['coverage_pct']}%)"
                )
            if concept.get("distinct_unmatched_codes"):
                warnings.append(
                    f"{entity}: {concept['distinct_unmatched_codes']} distinct source code(s) have no match in the "
                    f"{e.vocabulary} vocabulary loaded here"
                )
            if concept.get("unrecognized_format_rows"):
                warnings.append(
                    f"{entity}: {concept['unrecognized_format_rows']} row(s) have codes in a format the "
                    f"'{concept['normalization']}' rule does not recognize"
                )
            if concept.get("multi_concept_rows"):
                warnings.append(
                    f"{entity}: {concept['multi_concept_rows']} row(s) map to more than one standard concept "
                    "(each becomes a separate record)"
                )
            if concept.get("ambiguous_key_rows"):
                warnings.append(
                    f"{entity}: {concept['ambiguous_key_rows']} row(s) use a normalized code shared by several "
                    "vocabulary codes; only exact spellings were mapped"
                )
            if concept.get("unknown_concept_id_rows"):
                warnings.append(
                    f"{entity}: {concept['unknown_concept_id_rows']} row(s) have concept ids that are not in the "
                    "vocabulary loaded here"
                )
            if concept.get("non_standard_concept_rows"):
                warnings.append(
                    f"{entity}: {concept['non_standard_concept_rows']} row(s) use non-standard concept ids "
                    "(criteria use standard concepts and their descendants)"
                )
            if values.get("missing_value"):
                warnings.append(f"{entity}: {values['missing_value']} usable row(s) have no numeric value")
            if values.get("unmapped_unit"):
                warnings.append(
                    f"{entity}: {values['unmapped_unit']} row(s) with a value have no recognized unit; value "
                    "thresholds will not match them"
                )
            if orphans:
                warnings.append(
                    f"{entity}: {orphans} patient(s) are missing from the person table and cannot enter cohorts"
                )
        if m.observation.mode != "none":
            observed = fetch_count(con, f"SELECT count(DISTINCT person_id) FROM {qi(sem)}.observation_period")
            checks["observation"] = {"persons_with_observation": observed}
            if m.observation.mode == "table":
                ob = m.observation
                total = fetch_count(con, f"SELECT count(*) FROM {qi(stg)}.{qi(ob.table or '')}")
                valid = fetch_count(con, f"SELECT count(*) FROM {qi(sem)}.observation_period")
                checks["observation"].update(staged_rows=total, usable_rows=valid)
                if valid < total:
                    warnings.append(
                        f"observation: {total - valid} of {total} period row(s) excluded (missing or invalid dates, "
                        "or end before start)"
                    )
            if observed == 0:
                errors.append("no usable observation periods")
            elif observed < persons:
                warnings.append(f"{persons - observed} person(s) have no observation period and cannot enter cohorts")
        for rel in m.relationships:
            orphan = fetch_count(
                con,
                f"SELECT count(*) FROM {qi(stg)}.{qi(rel.from_table)} a WHERE a.{qi(rel.from_column)} IS NOT NULL "
                f"AND NOT EXISTS (SELECT 1 FROM {qi(stg)}.{qi(rel.to_table)} b WHERE CAST(b.{qi(rel.to_column)} AS "
                f"VARCHAR) = CAST(a.{qi(rel.from_column)} AS VARCHAR))",
            )
            key = f"relationship {rel.from_table}.{rel.from_column}->{rel.to_table}.{rel.to_column}"
            checks[key] = {"orphans": orphan}
            if orphan:
                warnings.append(
                    f"relationship {rel.from_table}.{rel.from_column} -> {rel.to_table}.{rel.to_column}: "
                    f"{orphan} row(s) have no match"
                )
        checks["surrogate_person_ids"] = use_map
        return checks, errors, warnings

    def _concept_checks(
        self, e: EntityMapping, x: EntityExprs, tbl: str, ok: str, sem: str, vs: str, usable: int
    ) -> dict[str, Any]:
        con = self.con
        if x.code_raw and e.vocabulary:
            strategy = normalization_for(e.vocabulary, e.code_normalization)
            n = f"(SELECT count(DISTINCT c.concept_id) FROM {qi(sem)}.code_map c WHERE {x.code_match})"
            amb = (
                f"EXISTS (SELECT 1 FROM {qi(sem)}.code_map c WHERE c.code_key = {x.code_key} AND c.ambiguous "
                f"AND c.vocabulary_id = {_vocab_lit(e.vocabulary)} AND c.strategy = '{strategy}')"
            )
            r = con.execute(
                f"WITH u AS (SELECT CAST({x.code_raw} AS VARCHAR) AS raw, {x.code_key} AS k, {n} AS n, {amb} AS amb "
                f"FROM {tbl} WHERE {ok}) SELECT "
                "count(*) FILTER (WHERE n > 0), count(*) FILTER (WHERE raw IS NULL), "
                "count(*) FILTER (WHERE raw IS NOT NULL AND k IS NULL), count(*) FILTER (WHERE n > 1), "
                "count(*) FILTER (WHERE amb), count(DISTINCT raw), count(DISTINCT raw) FILTER (WHERE n = 0), "
                "(SELECT count(*) FROM (SELECT k FROM u WHERE k IS NOT NULL GROUP BY k "
                "HAVING count(DISTINCT raw) > 1)) "
                "FROM u"
            ).fetchone()
            mapped, missing, unrec, multi, amb_rows, distinct, unmatched, merged = (int(v) for v in (r or (0,) * 8))
            return {
                "method": "source_code",
                "vocabulary": e.vocabulary,
                "normalization": strategy,
                "mapped_rows": mapped,
                "unmapped_rows": usable - mapped,
                "missing_code_rows": missing,
                "unrecognized_format_rows": unrec,
                "multi_concept_rows": multi,
                "ambiguous_key_rows": amb_rows,
                "distinct_codes": distinct,
                "distinct_unmatched_codes": unmatched,
                "codes_with_several_spellings": merged,
                "coverage_pct": round(100.0 * mapped / usable, 1) if usable else 0.0,
            }
        c = x.concept_raw
        r = con.execute(
            f"WITH u AS (SELECT CAST({c} AS BIGINT) AS cid FROM {tbl} WHERE {ok}) SELECT "
            "count(*) FILTER (WHERE cid IS NULL OR cid = 0), "
            f"count(*) FILTER (WHERE cid <> 0 AND NOT EXISTS (SELECT 1 FROM {vs}.concept k WHERE k.concept_id = cid)), "
            f"count(*) FILTER (WHERE EXISTS (SELECT 1 FROM {vs}.concept k WHERE k.concept_id = cid AND "
            "coalesce(k.standard_concept, '') <> 'S')), count(DISTINCT cid) FROM u"
        ).fetchone()
        missing, unknown, non_std, distinct = (int(v) for v in (r or (0,) * 4))
        mapped = usable - missing - unknown
        return {
            "method": "concept_id",
            "mapped_rows": mapped,
            "unmapped_rows": usable - mapped,
            "missing_concept_rows": missing,
            "unknown_concept_id_rows": unknown,
            "non_standard_concept_rows": non_std,
            "distinct_concept_ids": distinct,
            "coverage_pct": round(100.0 * mapped / usable, 1) if usable else 0.0,
        }

    # ---- profile files ------------------------------------------------------------------------------
    def _write_file(self, final: Path, body: dict[str, Any]) -> None:
        """Write via a temp file in the same directory + rename (no partially written profile is ever visible)."""
        self.local_dir.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=self.local_dir, prefix=".tmp-", suffix=".yaml")
        try:
            with os.fdopen(fd, "w") as fh:
                fh.write(PROFILE_HEADER)
                yaml.safe_dump(body, fh, sort_keys=False)
            self._replace(tmp, final)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise

    def _file_matches(self, path: Path, expected_hash: str | None, dataset: str) -> bool:
        try:
            body = yaml.safe_load(path.read_text())
        except (OSError, yaml.YAMLError):
            return False
        if not isinstance(body, dict) or expected_hash is None:
            return False
        b = _profile_body(body)
        return expected_hash in (sha(b), sha({**b, "name": dataset}))

    def _latest_registered(self, dataset: str) -> int | None:
        row = self.con.execute(
            "SELECT max(version) FROM meta.dataset_version WHERE dataset = ? AND status = 'registered'", [dataset]
        ).fetchone()
        return int(row[0]) if row and row[0] is not None else None

    def _publish(self, dataset: str, version: int, ingest_id: str, profile: dict[str, Any]) -> None:
        """After the commit: pinned file -> status 'registered' -> latest pointer. Failures leave a state that
        activation refuses and `reconcile()` repairs."""
        pinned = self.local_dir / f"{dataset}__v{version}.yaml"
        try:
            self._write_file(pinned, {**profile, "name": f"{dataset}__v{version}"})
            if not self._file_matches(pinned, profile_hash(profile), dataset):
                raise OSError("profile file did not verify after writing")
            self.con.execute(
                "UPDATE meta.dataset_version SET status='registered', registered_at=?, errors_json=NULL "
                "WHERE ingest_id=?",
                [now(), ingest_id],
            )
        except Exception as exc:
            problems = [{"code": "profile_publish_failed", "message": f"{type(exc).__name__} writing the profile"}]
            try:
                self.con.execute(
                    "UPDATE meta.dataset_version SET status='profile_failed', errors_json=? WHERE ingest_id=?",
                    [dumps(problems), ingest_id],
                )
            except duckdb.Error:
                pass  # stays 'profile_pending'; reconcile handles both states
            raise IngestError(
                f"{dataset} v{version}: data and mapping are stored, but the dataset profile could not be "
                f"published ({type(exc).__name__}); it is NOT selectable until `cohort-builder csv reconcile` succeeds",
                problems,
            ) from exc
        try:
            self._update_pointer(dataset)
        except Exception as exc:
            raise IngestError(
                f"{dataset} v{version} is registered (select it as {dataset}__v{version}), but the latest pointer "
                f"{dataset}.yaml could not be updated ({type(exc).__name__}); run `cohort-builder csv reconcile`",
                [{"code": "pointer_update_failed", "message": f"{type(exc).__name__} writing the pointer"}],
            ) from exc

    def _update_pointer(self, dataset: str) -> str:
        """Make <dataset>.yaml the profile of the latest registered version. Returns the action taken."""
        latest = self._latest_registered(dataset)
        pointer = self.local_dir / f"{dataset}.yaml"
        if latest is None:
            if pointer.is_file() and self._generated_for(pointer, dataset):
                pointer.unlink()
                return "removed"
            return "none"
        row = self.con.execute(
            "SELECT profile_json, profile_hash FROM meta.dataset_version WHERE dataset = ? AND version = ? "
            "AND status = 'registered'",
            [dataset, latest],
        ).fetchone()
        assert row is not None
        if self._file_matches(pointer, row[1], dataset) and self._pointer_version(pointer) == latest:
            return "ok"
        if row[0] is None:  # registered before profiles were stored in the database
            pinned = self.local_dir / f"{dataset}__v{latest}.yaml"
            if not self._file_matches(pinned, row[1], dataset):
                raise IngestError(f"{dataset} v{latest}: no stored profile to rebuild from; re-import the data")
            body = yaml.safe_load(pinned.read_text())
        else:
            body = json.loads(row[0])
        self._write_file(pointer, {**body, "name": dataset})
        return "written"

    @staticmethod
    def _pointer_version(path: Path) -> int | None:
        try:
            body = yaml.safe_load(path.read_text())
            return int(body["source"]["version"])
        except (OSError, yaml.YAMLError, KeyError, TypeError, ValueError):
            return None

    @staticmethod
    def _generated_for(path: Path, dataset: str) -> bool:
        try:
            body = yaml.safe_load(path.read_text())
        except (OSError, yaml.YAMLError):
            return path.read_text(errors="replace").startswith(PROFILE_HEADER) if path.is_file() else False
        src = body.get("source") if isinstance(body, dict) else None
        return isinstance(src, dict) and src.get("kind") == "csv" and src.get("dataset") == dataset

    # ---- recovery -----------------------------------------------------------------------------------
    def reconcile(
        self, actor: str, dataset: str | None = None, abandoned_after_minutes: int = ABANDONED_AFTER_MINUTES
    ) -> dict[str, Any]:
        """Bring profile files in line with the database (counts and versions only, never data):
        - 'allocating' rows older than `abandoned_after_minutes` -> failed; younger ones may belong to an
          import that is still running and are only reported ('left_in_progress'); same age rule for temp files
        - 'profile_pending' / 'profile_failed' -> published from the stored profile, then 'registered'
        - registered versions whose file is missing or modified -> rewritten from the stored profile
        - generated files of versions that are not registered -> removed (files we did not generate are kept)
        - the latest pointer -> repaired."""
        if dataset is not None:
            validate_name(dataset, "dataset name")
            names = [dataset]
        else:
            names = [
                r[0]
                for r in self.con.execute("SELECT DISTINCT dataset FROM meta.dataset_version ORDER BY 1").fetchall()
            ]
        actions: list[dict[str, Any]] = []
        problems: list[dict[str, Any]] = []
        if abandoned_after_minutes < 0:
            raise IngestError("abandoned_after_minutes must be >= 0")
        cutoff = now() - timedelta(minutes=abandoned_after_minutes)
        if self.local_dir.is_dir():
            for tmp in self.local_dir.glob(".tmp-*.yaml"):
                age_min = (time.time() - tmp.stat().st_mtime) / 60
                if age_min >= abandoned_after_minutes:
                    tmp.unlink(missing_ok=True)
                    actions.append({"action": "removed_temp_file"})
        for name in names:
            rows = self.con.execute(
                "SELECT ingest_id, version, status, profile_json, profile_hash, created_at FROM "
                "meta.dataset_version WHERE dataset = ? ORDER BY version",
                [name],
            ).fetchall()
            for ingest_id, version, status, pjson, phash, created_at in rows:
                where = {"dataset": name, "version": version}
                recent = created_at is None or created_at > cutoff
                if status == "allocating" and abandoned_after_minutes > 0 and recent:
                    actions.append({**where, "action": "left_in_progress"})
                elif status == "allocating":
                    self._mark_failed(ingest_id, [{"code": "abandoned", "message": "import did not finish"}], None)
                    actions.append({**where, "action": "marked_failed"})
                elif status in ("profile_pending", "profile_failed"):
                    if pjson is None:
                        problems.append({**where, "problem": "no stored profile; re-import"})
                        continue
                    try:
                        self._publish(name, version, ingest_id, json.loads(pjson))
                        actions.append({**where, "action": "published"})
                    except IngestError as exc:
                        problems.append({**where, "problem": exc.problems[0]["code"] if exc.problems else "error"})
                elif status == "registered":
                    pinned = self.local_dir / f"{name}__v{version}.yaml"
                    if self._file_matches(pinned, phash, name):
                        continue
                    if pjson is None:
                        problems.append({**where, "problem": "profile file missing or modified; no stored profile"})
                        continue
                    self._write_file(pinned, {**json.loads(pjson), "name": f"{name}__v{version}"})
                    actions.append({**where, "action": "rewrote_profile"})
            registered = {int(v) for _i, v, st, _p, _h, _c in rows if st == "registered"}
            registered |= {
                int(r[0])
                for r in self.con.execute(
                    "SELECT version FROM meta.dataset_version WHERE dataset = ? AND status = 'registered'", [name]
                ).fetchall()
            }
            if self.local_dir.is_dir():
                for f in sorted(self.local_dir.glob(f"{name}__v*.yaml")):
                    suffix = f.stem.removeprefix(f"{name}__v")
                    if suffix.isdigit() and int(suffix) not in registered and self._generated_for(f, name):
                        f.unlink()
                        actions.append({"dataset": name, "version": int(suffix), "action": "removed_stale_profile"})
            try:
                result = self._update_pointer(name)
                if result != "ok" and result != "none":
                    actions.append({"dataset": name, "action": f"pointer_{result}"})
            except (IngestError, OSError) as exc:
                problems.append({"dataset": name, "problem": f"pointer: {type(exc).__name__}"})
        self.store.audit(
            actor,
            "dataset.reconcile",
            "dataset",
            dataset or "*",
            "success" if not problems else "partial",
            None,
            {"actions": len(actions), "problems": len(problems)},
        )
        return {"actions": actions, "problems": problems}

    def _mark_failed(self, ingest_id: str, problems: list[dict[str, Any]], files: list[dict[str, Any]] | None) -> None:
        file_rows = (
            dumps([{k: f[k] for k in ("table", "file", "sha256", "rows")} for f in files])
            if files is not None
            else None
        )
        self.con.execute(
            "UPDATE meta.dataset_version SET status='failed', errors_json=?, files_json=coalesce(?, files_json) "
            "WHERE ingest_id=?",
            [dumps(problems[:50]), file_rows, ingest_id],
        )

    # ---- reads -----------------------------------------------------------------------------------
    def list_datasets(self) -> list[dict[str, Any]]:
        names = [
            r[0] for r in self.con.execute("SELECT DISTINCT dataset FROM meta.dataset_version ORDER BY 1").fetchall()
        ]
        out = []
        for n in names:
            versions = self.versions(n)
            usable = [v for v in versions if v["status"] in USABLE]
            latest = usable[0] if usable else versions[0]
            out.append(
                {
                    "dataset": n,
                    "latest_version": latest["version"],
                    "status": latest["status"],
                    "versions": len(versions),
                    "selectable": self._selectable(n),
                }
            )
        return out

    def _selectable(self, dataset: str) -> bool:
        path = self.local_dir / f"{dataset}.yaml"
        if not path.is_file():
            return False
        try:
            verify_registered_profile(self.con, yaml.safe_load(path.read_text()) or {}, dataset)
        except (ValueError, yaml.YAMLError, AttributeError):
            return False
        return True

    def info(self, dataset: str) -> dict[str, Any]:
        versions = self.versions(dataset)
        if not versions:
            raise KeyError(f"dataset {dataset!r} not found")
        profile_path = self.local_dir / f"{dataset}.yaml"
        selectable = self._selectable(dataset)
        profile = yaml.safe_load(profile_path.read_text()) if selectable else None
        return {
            "dataset": dataset,
            "selectable_as": dataset if profile else None,
            "capabilities": profile["capabilities"] if profile else None,
            "source": profile.get("source") if profile else None,
            "versions": [
                {
                    k: v[k]
                    for k in (
                        "version",
                        "status",
                        "created_by",
                        "created_at",
                        "registered_at",
                        "staging_schema",
                        "semantic_schema",
                        "mapping_hash",
                        "snapshot",
                        "software_version",
                        "files",
                        "validation",
                        "errors",
                    )
                }
                for v in versions
            ],
        }
